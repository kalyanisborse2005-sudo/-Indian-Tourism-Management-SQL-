CREATE DATABASE Indian_Tourism_Management;
USE Indian_Tourism_Management;
CREATE TABLE Tourists (
    tourist_id INT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    gender VARCHAR(20),
    age INT,
    nationality VARCHAR(50),
    state VARCHAR(50),
    city VARCHAR(50)
);
CREATE TABLE Destinations (
    destination_id INT PRIMARY KEY,
    destination_name VARCHAR(100) NOT NULL,
    state VARCHAR(50) NOT NULL,
    region VARCHAR(30),
    destination_type VARCHAR(50),
    entry_fee DECIMAL(10,2)
);
CREATE TABLE Hotels (
    hotel_id INT PRIMARY KEY,
    hotel_name VARCHAR(100) NOT NULL,
    destination_id INT,
    hotel_category VARCHAR(30),
    room_price DECIMAL(10,2),
    total_rooms INT,
    FOREIGN KEY (destination_id)
        REFERENCES Destinations(destination_id)
);
CREATE TABLE Tour_Packages (
    package_id INT PRIMARY KEY,
    package_name VARCHAR(100) NOT NULL,
    destination_id INT,
    duration_days INT,
    package_price DECIMAL(10,2),
    package_type VARCHAR(50),
    FOREIGN KEY (destination_id)
        REFERENCES Destinations(destination_id)
);
CREATE TABLE Bookings (
    booking_id INT PRIMARY KEY,
    tourist_id INT,
    package_id INT,
    hotel_id INT,
    booking_date DATE,
    check_in DATE,
    check_out DATE,
    number_of_people INT,
    booking_status VARCHAR(30),

    FOREIGN KEY (tourist_id)
        REFERENCES Tourists(tourist_id),

    FOREIGN KEY (package_id)
        REFERENCES Tour_Packages(package_id),

    FOREIGN KEY (hotel_id)
        REFERENCES Hotels(hotel_id)
);
CREATE TABLE Payments (
    payment_id INT PRIMARY KEY,
    booking_id INT,
    payment_date DATE,
    amount DECIMAL(12,2),
    payment_method VARCHAR(30),
    payment_status VARCHAR(30),

    FOREIGN KEY (booking_id)
        REFERENCES Bookings(booking_id)
);
CREATE TABLE Reviews (
    review_id INT PRIMARY KEY,
    tourist_id INT,
    destination_id INT,
    rating DECIMAL(2,1),
    review_text VARCHAR(500),
    review_date DATE,

    FOREIGN KEY (tourist_id)
        REFERENCES Tourists(tourist_id),

    FOREIGN KEY (destination_id)
        REFERENCES Destinations(destination_id)
);
